#!/bin/bash
# یادداشت‌های من از دستور ls
# LPIC-1

ls          # لیست فایل‌ها و پوشه‌ها
ls -l       # نمایش جزئیات کامل (مالک، حجم، تاریخ، دسترسی‌ها)
ls -a       # نمایش فایل‌های مخفی هم (اونایی که با . شروع می‌شن)
ls -la      # ترکیب هردو، همه‌چیز رو یه‌جا نشون میده
ls -h       # حجم فایل‌ها رو خوانا نشون میده (مثل 2K یا 5M)
ls -lh      # ترکیب جزئیات کامل + حجم خوانا
